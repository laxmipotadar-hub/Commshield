"""End-to-end integration test for the CommShield pipeline.

Runs a scenario through the whole pipeline using the test client and verifies:
1. Database reset preserves anchor baselines while clearing runtime tables.
2. Canonical traffic windows are ingested and stored.
3. Multi-model detector triggers at least one anomaly alert.
4. Drift attribution evaluates the shift and records a decision trace.
5. The active serving baseline is completely unchanged unless explicitly approved.
6. Post analyst approval, atomic promotion updates the active baseline.
7. Concurrent replay attempts refuse to start twice with a clear 409 message.
"""

import sys
from pathlib import Path
import pytest
from httpx import ASGITransport, AsyncClient

backend_dir = Path(__file__).resolve().parent.parent
if str(backend_dir) not in sys.path:
    sys.path.insert(0, str(backend_dir))

from app.main import app
from app.database import SessionLocal
from app.services.replay import replay_service


@pytest.fixture
async def client():
    async with AsyncClient(
        transport=ASGITransport(app=app), base_url="http://test"
    ) as ac:
        yield ac


@pytest.mark.anyio
async def test_commshield_pipeline_end_to_end(client: AsyncClient):
    # 1. Reset runtime database cleanly
    res_reset = await client.post("/api/reset")
    assert res_reset.status_code == 200
    reset_data = res_reset.json()
    assert reset_data["status"] == "SUCCESS"

    # Verify baseline is currently the active anchor
    res_base = await client.get("/api/baselines?slice_id=sst-1-sd-010203")
    assert res_base.status_code == 200
    baselines = res_base.json()
    assert len(baselines) >= 1
    active_b = [b for b in baselines if b.get("is_active") is True]
    assert len(active_b) == 1
    initial_version = active_b[0]["version"]
    assert initial_version == "v1.0.0-anchor"

    # 2. Run a short scenario through the whole pipeline synchronously
    # Process 20 windows of legitimate_growth
    db = SessionLocal()
    try:
        processed_count = replay_service.start_sync(
            dataset_id="legitimate_growth",
            max_windows=20,
            db=db,
        )
        assert processed_count >= 15
    finally:
        db.close()

    # 3. Verify canonical windows are stored in the database
    res_windows = await client.get("/api/traffic/windows?limit=50")
    assert res_windows.status_code == 200
    windows_data = res_windows.json()
    assert windows_data["total"] >= 15
    assert len(windows_data["items"]) >= 15

    # 4. Verify at least one anomaly alert was generated
    res_alerts = await client.get("/api/alerts?limit=50")
    assert res_alerts.status_code == 200
    alerts = res_alerts.json()
    assert len(alerts) >= 1
    first_alert = alerts[0]
    assert "detector_output" in first_alert
    assert "window_id" in first_alert
    assert "slice_id" in first_alert

    # 5. Verify at least one attribution with a decision trace exists
    res_traces = await client.get("/api/decision-traces?limit=10")
    assert res_traces.status_code == 200
    traces = res_traces.json()
    assert len(traces) >= 1
    first_trace = traces[0]
    assert "id" in first_trace
    assert "action" in first_trace
    assert len(first_trace["steps"]) > 0

    # 6. Verify that the active baseline is UNCHANGED unless approved
    res_base_check = await client.get("/api/baselines?slice_id=sst-1-sd-010203")
    assert res_base_check.status_code == 200
    active_check = [b for b in res_base_check.json() if b.get("is_active") is True]
    assert len(active_check) == 1
    assert active_check[0]["version"] == initial_version
    assert active_check[0]["is_anchor"] is True

    # 7. Check for pending shadow candidate baseline generated by governance
    res_cand = await client.get("/api/candidates?status=PENDING")
    assert res_cand.status_code == 200
    candidates = res_cand.json()

    if len(candidates) > 0:
        cand_to_approve = candidates[0]
        # Approve the candidate
        res_appr = await client.post(
            f"/api/v1/candidates/{cand_to_approve['id']}/approve",
            json={
                "analyst_id": "lead_sec_analyst",
                "notes": "Verified organic traffic expansion across eMBB slice.",
            },
        )
        assert res_appr.status_code == 200
        assert res_appr.json()["status"] == "APPROVED"

        # After approval, active baseline should now reflect the approved version
        res_base_post = await client.get("/api/baselines?slice_id=sst-1-sd-010203")
        assert res_base_post.status_code == 200
        active_post = [b for b in res_base_post.json() if b.get("is_active") is True]
        assert len(active_post) == 1
        assert active_post[0]["version"] == cand_to_approve["candidate_version"]

    # 8. Test refusal when starting replay twice concurrently
    # Start async replay
    payload = {
        "dataset_id": "legitimate_growth",
        "speed_multiplier": 5.0,
        "active_arms": ["arm_a_static"],
        "window_scale_sec": 60,
    }
    res_start = await client.post("/api/v1/replay/start", json=payload)
    assert res_start.status_code == 200

    # Attempting to start concurrently must return HTTP 409
    res_conflict = await client.post("/api/v1/replay/start", json=payload)
    assert res_conflict.status_code == 409
    assert "already running" in res_conflict.json()["detail"].lower()

    # Clean up replay
    await client.post("/api/v1/replay/stop")
